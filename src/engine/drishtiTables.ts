/**
 * drishtiTables.ts — గ్రహ స్ఫుట దృష్టి పట్టిక (ఒకే నిజం)
 * ==================================================
 * బృహత్ పరాశర హోరా శాస్త్రం అధ్యాయం 26 (గ్రహ స్ఫుట దృష్టి) + సారావళి
 * స్ఫుట దృష్టి పట్టిక. విరూపాలు 0…60 (60 = పూర్ణ దృష్టి).
 *
 * సాధారణ నియమం: 30°–60° = (a−30)/2 · 60°–90° = a−45 · 90°–120° = 30+(120−a)/2 ·
 * 120°–150° = 150−a · 150°–180° = 2(a−150) · 180°–300° = (300−a)/2 · 300°+ = 0.
 * విశేష దృష్టులు: శని 3/10 (60°, 270°), కుజుడు 4/8 (90°–120°, 210°–240°),
 * గురువు 5/9 (120°–150°, 240°–270°) — ఆ వంతులలో పూర్ణ బలం వరకు పెరుగుతాయి.
 *
 * ఇది షడ్బలంలోని దృక్ బలం (drikBalaVirupas, వి.పి. జైన్/బి.వి. రామన్ పట్టికలు)
 * కంటే వేరు — అది నికర దృష్టి (శుభ/పాప సమాహారం), ఇది ఒక జంట మధ్య దృష్టి బలం.
 */

import { norm360 } from './astroCore.ts';

export function sputaDrishti(aspectingId: string, aspectAngle: number): number {
  const a = norm360(aspectAngle);
  const special = aspectingId === 'Mars' || aspectingId === 'Jupiter' || aspectingId === 'Saturn';
  if (a < 30 || a >= 330) return 0;
  // 30–60: సాధారణ (a−30)/2; శనికి ద్విగుణం
  if (a < 60) return aspectingId === 'Saturn' ? (a - 30) * 2 : (a - 30) / 2;
  // 60–90: a−45; శనికి 45 + (90−a)/2
  if (a < 90) return aspectingId === 'Saturn' ? 45 + (90 - a) / 2 : a - 45;
  // 90–120: 30 + (120−a)/2; కుజ/గురులకు 45 + (a−90)/2
  if (a < 120) return special && aspectingId !== 'Saturn' ? 45 + (a - 90) / 2 : 30 + (120 - a) / 2;
  // 120–150: 150−a; కుజ/గురులకు ద్విగుణం
  if (a < 150) return special && aspectingId !== 'Saturn' ? 2 * (150 - a) : 150 - a;
  // 150–180: (a−150)·2
  if (a < 180) return (a - 150) * 2;
  // 180–210: (300−a)/2; కుజుడు 8వ దృష్టి పూర్ణం (210°)
  if (a < 210) return aspectingId === 'Mars' ? 60 : (300 - a) / 2;
  // 210–240: (300−a)/2; కుజుడు 270−a; గురువు 45 + (a−210)/2
  if (a < 240) {
    if (aspectingId === 'Mars') return 270 - a;
    if (aspectingId === 'Jupiter') return 45 + (a - 210) / 2;
    return (300 - a) / 2;
  }
  // 240–270: (300−a)/2; గురువు 15 + 2·(270−a)/3; శని a−210
  if (a < 270) {
    // ప్రచురిత పట్టిక ఇక్కడ 15+2(270−a)/3 ఇస్తుంది; కానీ గురువు 9వ దృష్టి 240°లో పూర్ణం (60)
    // కాబట్టి ఆ పట్టిక 240° వద్ద అంతరాయం చూపుతుంది. 60 → 15 ఏకరీతి ఇంటర్పొలేషన్ తీసుకున్నాము
    // (ఇరువైపులా నిరంతరం; మూలం: బృహత్ పరాశర అ.26 + సారావళి స్ఫుట దృష్టి పట్టిక).
    if (aspectingId === 'Jupiter') return 60 - 1.5 * (a - 240);
    if (aspectingId === 'Saturn') return a - 210;
    return (300 - a) / 2;
  }
  // 270–300: సాధారణం (300−a)/2; శనికి 10వ దృష్టి పూర్ణం (270°), తర్వాత ద్విగుణ క్షయం
  if (a < 300) {
    if (aspectingId === 'Saturn') return 2 * (300 - a);
    return (300 - a) / 2;
  }
  // 300° దాటితే దృష్టి లేదు (బృహత్ పరాశర అ.26: పది రాశుల పైన దృష్టి శూన్యం)
  return 0;

}


export function computeAshtakavargaPhala(chart: CompleteChartResult): AvSamudayaReport {
  const sav = chart.ashtakavarga?.sarvashtakavarga ?? new Array(12).fill(0);
  const ascSign = chart.ascendant.signIndex;
  const planetById = new Map(chart.planets.map((p) => [p.id, p]));

  const rows: AvBhavaPhala[] = [];
  for (let h = 1; h <= 12; h += 1) {
    const signIndex = (ascSign + h - 1) % 12;
    const bindus = sav[signIndex] ?? 0;
    const band = bandOf(bindus);
    const lordTe = SIGN_LORDS_TE[signIndex];
    const lordPlanet = planetById.get(PLANET_ID_BY_LORD[lordTe]);
    const lordHouse = lordPlanet?.house ?? 0;
    rows.push({
      house: h,
      houseNameTe: HOUSE_NAMES_TE[h - 1],
      houseThemeTe: BHAVA_THEMES_TE[h - 1],
      signIndex,
      signTe: BHAVA_RASI_TE[signIndex],
      bindus,
      band,
      bandLabelTe: BAND_LABEL[band],
      bandRangeTe: BAND_RANGE[band],
      lordTe,
      lordPlacementTe: lordPlanet
        ? `${lordTe} ${BHAVA_RASI_TE[lordPlanet.d1Sign] ?? ''}లో ${lordHouse}వ భావంలో`
        : `${lordTe} (స్థితి లెక్కించబడలేదు)`,
      lordRasiBindus: sav[lordPlanet?.d1Sign ?? 0] ?? 0,
      phalaTe: PHALA_TE[h][band],
      pariharaTe: PARIHARA_TE[h],
    });
  }

  const bindusAll = rows.map((r) => r.bindus);
  const totalBindus = chart.ashtakavarga?.totalBindus ?? bindusAll.reduce((s, x) => s + x, 0);
  const kendra = [1, 4, 7, 10].map((h) => rows[h - 1].bindus);
  const trikona = [1, 5, 9].map((h) => rows[h - 1].bindus);
  const dusthana = [6, 8, 12].map((h) => rows[h - 1].bindus);
  const upachaya = [3, 6, 10, 11].map((h) => rows[h - 1].bindus);

  const sorted = [...rows].sort((a, b) => b.bindus - a.bindus);
  const strongRows = rows.filter((r) => r.band === 'strong');
  const weakRows = rows.filter((r) => r.band === 'weak');
  const strongest = sorted[0];
  const weakest = sorted[sorted.length - 1];

  const lagna = rows[0].bindus;
  const seventh = rows[6].bindus;
  const lagnaSeventhNoteTe =
    lagna > seventh
      ? `లగ్నానికి ${lagna}, సప్తమానికి ${seventh} బిందువులు — మీ స్వీయ నిర్ణయ శక్తి, వ్యక్తిత్వం భాగస్వామి ప్రభావం కంటే బలంగా నిలిచే సూచన. సంబంధాలలో మీరే నిర్ణయాధికారంగా ఉండే అవకాశం.`
      : lagna === seventh
        ? `లగ్నం మరియు సప్తమం రెండూ ${lagna} బిందువులు — ఆత్మ మరియు భాగస్వామి శక్తులు సమానం; సమన్వయ జీవితం సాధ్యం.`
        : `లగ్నానికి ${lagna}, సప్తమానికి ${seventh} బిందువులు — భాగస్వామి/భాగస్వామ్య బలం మీ స్వీయ వ్యక్తిత్వం కంటే ముందుండే సూచన. ఒప్పందాలు, భాగస్వామ్య వ్యవహారాలలో సంయుక్త నిర్ణయం శ్రేయస్కరం.`;

  const rasiSorted = sav
    .map((b, i) => ({ b, i }))
    .sort((x, y) => y.b - x.b);
  const topRasis = rasiSorted.slice(0, 3);
  const lowRasis = rasiSorted.slice(-2);
  const rasiRankingTe = `అత్యధిక బిందువులు — ${topRasis
    .map((r) => `${BHAVA_RASI_TE[r.i]} (${r.b})`)
    .join(', ')}; అత్యల్పం — ${lowRasis.map((r) => `${BHAVA_RASI_TE[r.i]} (${r.b})`).join(', ')}. సగటు ${avg(bindusAll)} బిందువులు (శాస్త్ర సగటు 28.08).`;

  const nakNotes: string[] = [];
  const seenNak = new Set<string>();
  for (const p of chart.planets) {
    if (!p.nakshatra || seenNak.has(p.nakshatra)) continue;
    seenNak.add(p.nakshatra);
    const b = sav[p.d1Sign] ?? 0;
    const band = bandOf(b);
    nakNotes.push(
      `${PLANET_TE[p.name] ?? p.name} — ${NAK_EN_TO_TE[p.nakshatra] ?? p.nakshatra} నక్షత్రం (${BHAVA_RASI_TE[p.d1Sign] ?? ''} రాశి, ${b} బిందువులు): ${
        band === 'strong'
          ? 'ఈ నక్షత్ర జన్ములకు ఆ రంగంలో సహజ ప్రోత్సాహం'
          : band === 'moderate'
            ? 'సమతుల్య ఫలితం; శ్రమతో సాధన'
            : 'కాస్త శ్రమ అవసరం; పరిహారం ఉపయోగకరం'
      }.`,
    );
  }

  const synthesisTe = [
    `మొత్తం సాముదాయిక అష్టకవర్గ బిందువులు ${totalBindus} (సగటు ${avg(bindusAll)}).`,
    strongRows.length
      ? `${strongRows.map((r) => `${r.house}వ భావం (${r.bindus})`).join(', ')} బలంగా ఉన్నందున ${
          strongRows.length >= 4
            ? 'జీవితంలో అనేక రంగాలలో ఏకకాల విజయం, సహజ అనుకూలత'
            : 'ముఖ్యమైన కొన్ని రంగాలలో నిర్ణాయక విజయం'
        } కలుగుతుంది.`
      : 'ప్రత్యేకంగా 30+ బిందువులు ఉన్న భావం లేదు — ఫలితాలు శ్రమ, క్రమశిక్షణపై ఆధారపడతాయి.',
    weakRows.length
      ? `${weakRows.map((r) => `${r.house}వ భావం (${r.bindus})`).join(', ')} బలహీనతకు సంబంధిత రంగాలలో ముందస్తు జాగ్రత్త, పరిహారం అవసరం.`
      : 'బలహీన భావాలు లేవు — సమస్త భావాలు కనీస మధ్యస్థ స్థాయి దాటాయి, ఇది అరుదైన శుభ స్థితి.',
    `కేంద్ర సగటు ${avg(kendra)}, త్రికోణ సగటు ${avg(trikona)}, దుష్ఠాన సగటు ${avg(dusthana)}, ఉపచయ సగటు ${avg(upachaya)}. ${
      avg(trikona) >= avg(dusthana)
        ? 'త్రికోణ బలం దుష్ఠాన బలం కంటే ఎక్కువ — భాగ్య, ధర్మ, పుత్ర రంగాలు రక్షణగా నిలుస్తాయి.'
        : 'దుష్ఠాన బలం ఎక్కువ — శత్రు–రోగ–ఋణ రంగాలలో అప్రమత్తత అవసరం.'
    }`,
    `అత్యధిక బిందువులు ${strongest.house}వ భావానికి (${strongest.signTe}, ${strongest.bindus}) — ఇది మీ జీవితంలో అత్యంత సహజంగా ఫలించే రంగం (${BHAVA_THEMES_TE[strongest.house - 1]}); అత్యల్పం ${weakest.house}వ భావం (${weakest.signTe}, ${weakest.bindus}) కాబట్టి అక్కడ కృత్రిమ ప్రయత్నం, నిపుణుల సలహా అవసరం.`,
  ].join(' ');

  return {
    rows,
    totalBindus,
    averageBindus: avg(bindusAll),
    bandCounts: { weak: weakRows.length, moderate: rows.filter((r) => r.band === 'moderate').length, strong: strongRows.length },
    strongHousesTe: strongRows.length ? strongRows.map((r) => `${r.house}`).join(', ') : '—',
    weakHousesTe: weakRows.length ? weakRows.map((r) => `${r.house}`).join(', ') : '—',
    kendraAvg: avg(kendra),
    trikonaAvg: avg(trikona),
    dusthanaAvg: avg(dusthana),
    upachayaAvg: avg(upachaya),
    strongestHouse: strongest.house,
    weakestHouse: weakest.house,
    lagnaBindus: lagna,
    seventhBindus: seventh,
    lagnaSeventhNoteTe,
    rasiRankingTe,
    nakshatraNotesTe: nakNotes,
    synthesisTe,
    classicalRuleTe:
      'సూత్రం (పరాశర / అష్టకవర్గ తత్త్వం): రాశి బిందువులు 30+ = బలమైనది, 25–29 = మధ్యస్థం, 24 లేదా తక్కువ = బలహీనం. సగటు 28.08 (337 ÷ 12). స్వగృహ బిందువులు మరియు గోచర గ్రహ బిందువుల సమన్వయంతో ఫలితం నిర్ణయించాలి; బలహీన భావానికి కూడా దాని అధిపతి బలం ఉంటే ఫలితం మెరుగుపడుతుంది.',
  };
}

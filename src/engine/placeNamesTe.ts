/** పోలిక కీ: lowercase, అక్షరాలు-అంకెలు మాత్రమే */
function placeKey(raw: string): string {
  return (raw ?? '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * స్థల నామాన్ని తెలుగులో ఇస్తుంది. తెలుగులో ఇచ్చినట్టయితే అలాగే,
 * పట్టికలో లేని ఆంగ్ల పేరు అయితే లిప్యంతరీకరణ.
 * ఉదా. "Hyderabad" → "హైదరాబాద్", "Bangalore (Bengaluru)" → "బెంగళూరు".
 */
export function placeNameTe(raw: string | undefined | null): string {
  const src = (raw ?? '').trim();
  if (!src) return '';
  if (/[\u0C00-\u0C7F]/.test(src)) return src;

  // "Hyderabad, India" / "Hyderabad (Telangana)" — మొదటి భాగం ప్రధాన స్థలం
  const head = src.split(/[,(/]/)[0].trim();
  const direct = PLACE_TE[placeKey(head)] ?? PLACE_TE[placeKey(src)];
  if (direct) return direct;

  // వికల్ప నామం బ్రాకెట్లలో ఉంటే (Bangalore (Bengaluru))
  const inner = src.match(/\(([^)]+)\)/)?.[1];
  if (inner) {
    const alt = PLACE_TE[placeKey(inner)];
    if (alt) return alt;
  }

  return latinToTelugu(head);
}

/** ఈ స్థలం పట్టికలో తెలిసినదా (పరీక్షల కోసం) */
export function isKnownPlaceTe(raw: string): boolean {
  const head = (raw ?? '').split(/[,(/]/)[0].trim();
  return Boolean(PLACE_TE[placeKey(head)]);
}
